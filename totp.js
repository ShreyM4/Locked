  // ---- TOTP Computation & Verification (RFC 6238) ----

  async function calculateOTP(secretBase32, timeStep) {
    const keyBytes = base32Decode(secretBase32);
    if (keyBytes.length === 0) return null;

    const cryptoKey = await crypto.subtle.importKey(
      'raw',
      keyBytes,
      { name: 'HMAC', hash: 'SHA-1' },
      false,
      ['sign']
    );

    const timeBuf = new ArrayBuffer(8);
    const view = new DataView(timeBuf);
    view.setUint32(0, Math.floor(timeStep / 0x100000000), false);
    view.setUint32(4, timeStep >>> 0, false);

    const signature = await crypto.subtle.sign('HMAC', cryptoKey, timeBuf);
    const sigBytes = new Uint8Array(signature);

    // Dynamic truncation (RFC 4226)
    const offset = sigBytes[19] & 0x0f;
    const binary =
      ((sigBytes[offset] & 0x7f) << 24) |
      ((sigBytes[offset + 1] & 0xff) << 16) |
      ((sigBytes[offset + 2] & 0xff) << 8) |
      (sigBytes[offset + 3] & 0xff);

    return String(binary % 1000000).padStart(6, '0');
  }

  async function verifyTOTP(token, secretBase32, windowSteps = 1) {
    if (!token || typeof token !== 'string') return false;
    const cleanToken = token.trim().replace(/\s+/g, '');
    if (!/^\d{6}$/.test(cleanToken)) return false;
    if (!secretBase32) return false;

    const currentStep = Math.floor(Date.now() / 1000 / 30);

    for (let offset = -windowSteps; offset <= windowSteps; offset++) {
      const step = currentStep + offset;
      const expected = await calculateOTP(secretBase32, step);
      if (expected && expected === cleanToken) {
        return true;
      }
    }
    return false;
  }

